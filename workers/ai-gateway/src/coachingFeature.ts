function isCompleteCoachingDraft(content: string | null): boolean {
  if (!content) return false;
  const clean = content.trim();
  if (clean.length < 120) return false;
  if (/(^|\n)```[^\n]*$/.test(clean)) return false;
  if (/[：:]$|[-*|]$|[([{]$/.test(clean)) return false;
  if (/\b(시작|예를 들어|다음과 같이|먼저)\s*[:：]$/.test(clean)) return false;
  return /[.!?。！？다요죠습니다함]$/.test(clean);
}

async function requestGateway(
  messages: Array<{ role: "system" | "user"; content: string }>,
  _env: Record<string, string | undefined>,
  maxTokens = 3000,
) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 30000);
  try {
    const response = await fetch("https://gnhweb-ai-gateway.gemini19840314.workers.dev", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        task: "student-council",
        messages,
        max_tokens: maxTokens,
      }),
      signal: controller.signal,
    });
    if (!response.ok) return null;
    const data = await response.json() as { choices?: Array<{ message?: { content?: unknown } }> };
    const content = data.choices?.[0]?.message?.content;
    return typeof content === "string" && content.trim().length >= 40 ? content.trim() : null;
  } catch (error) {
    console.error("[ai-gateway] coaching provider error", error);
    return null;
  } finally {
    clearTimeout(timeout);
  }
}

export async function handleNimCoaching(req: Request, env: Record<string, string | undefined>) {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  if (req.method !== "POST") return json({ error: "POST only" }, 405);

  try {
    const body = await req.json() as { concern?: unknown; tone?: unknown };
    const concern = typeof body.concern === "string" ? body.concern.trim().slice(0, 2600) : "";
    const tone = body.tone === "empathetic" ? "empathetic" : "direct";
    if (!concern) return json({ error: "고민 내용을 입력해주세요." }, 400);

    const coachingLens = COACHING_LENSES[Math.floor(Math.random() * COACHING_LENSES.length)];
    const coachingMethod = COACHING_METHODS[Math.floor(Math.random() * COACHING_METHODS.length)];
    const generationNonce = crypto.randomUUID();

    const diagnosisRaw = await requestGateway([
      { role: "system", content: buildDiagnosisPrompt() },
      {
        role: "user",
        content: `원래 고민:\n${concern}\n\n이번 진단 관점: ${coachingLens}\n이번 진단 식별자: ${generationNonce}`,
      },
    ], env, 1800);

    const diagnosis = diagnosisRaw ? parseDiagnosis(diagnosisRaw) : null;

    const finalMessages = [
      { role: "system" as const, content: `${buildSystemPrompt(tone)}\n${buildFinalPrompt(tone)}` },
      {
        role: "user" as const,
        content: `원래 고민:\n${concern}\n\n진단 자료:\n${diagnosis ? JSON.stringify(diagnosis) : "구조화된 진단을 얻지 못했으므로 원래 고민을 직접 다시 분석한다."}\n\n이번 사고 관점: ${coachingLens}\n이번 답변 방식: ${coachingMethod}\n이번 생성 식별자: ${generationNonce}\n\n위 자료와 원래 고민을 대조한 뒤, 원래 고민에 가장 적합한 새로운 최종 코칭 답변을 작성해라. 진단 자료의 표현을 그대로 복사하지 말고, 실제 판단이 필요한 부분은 다시 생각해서 작성한다. 성경적 원칙을 실제 판단과 행동에 반영하고, 사명자로서 사용자가 놓친 점과 지금 옳은 행동을 근거가 있을 때 분명히 제시해라.`,
      },
    ];

    let finalDraft = await requestGateway(finalMessages, env, 4000);

    if (finalDraft && !isCompleteCoachingDraft(finalDraft)) {
      finalDraft = await requestGateway([
        ...finalMessages,
        {
          role: "user",
          content: "방금 생성된 답변이 미완성으로 끝났을 가능성이 있다. 이전 답변을 이어 쓰지 말고 처음부터 다시 작성해라. 핵심 판단, 사명자로서 놓친 부분과 옳은 행동(해당되는 경우), 성경적 원칙의 실제 적용, 사용자와 상대의 책임 구분, 실제 행동까지 포함하고 마지막은 완전한 문장으로 끝내라. 날짜·도구·조직 절차·상대의 심리나 신앙 상태를 임의로 만들지 마라.",
        },
      ], env, 4000);
    }

    if (finalDraft && isCompleteCoachingDraft(finalDraft)) return json({ advice: finalDraft });
    if (finalDraft) return json({ advice: finalDraft });
    return json({ advice: tone === "direct" ? FALLBACK_DIRECT : FALLBACK_EMPATHETIC });
  } catch (error) {
    console.error("nim-coaching error", error);
    return json({ advice: tone === "direct" ? FALLBACK_DIRECT : FALLBACK_EMPATHETIC });
  }
}
